-- 1. Roles
CREATE TABLE IF NOT EXISTS employee_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- 2. Employee accounts
CREATE TABLE IF NOT EXISTS employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES employee_role(role_id)
        ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL,
    id_number VARCHAR(30) NOT NULL UNIQUE,
    phone_number VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT employee_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0)
);

-- 3. Requester accounts
CREATE TABLE IF NOT EXISTS requester (
    requester_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT requester_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0)
);

-- Emails are unique within each account table.
-- Email comparison is case-insensitive.
CREATE UNIQUE INDEX IF NOT EXISTS uq_employee_email_lower
    ON employee (LOWER(email));

CREATE UNIQUE INDEX IF NOT EXISTS uq_requester_email_lower
    ON requester (LOWER(email));

-- 4. Service categories
CREATE TABLE IF NOT EXISTS service_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT category_type_not_blank
        CHECK (LENGTH(TRIM(type)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_category_type_lower
    ON service_category (LOWER(type));

-- 5. Request statuses
CREATE TABLE IF NOT EXISTS request_status (
    status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- 6. Main service requests
CREATE TABLE IF NOT EXISTS service_request (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES requester(requester_id)
        ON DELETE RESTRICT,
    category_id BIGINT NOT NULL REFERENCES service_category(category_id)
        ON DELETE RESTRICT,
    assigned_employee_id BIGINT REFERENCES employee(employee_id)
        ON DELETE RESTRICT,
    current_status_id BIGINT NOT NULL REFERENCES request_status(status_id)
        ON DELETE RESTRICT,
    description TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    due_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at TIMESTAMPTZ,
    CONSTRAINT request_description_not_blank
        CHECK (LENGTH(TRIM(description)) > 0),
    CONSTRAINT request_due_after_submission
        CHECK (due_at >= submitted_at)
);

-- 7. Append-only status history
CREATE TABLE IF NOT EXISTS request_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_request(request_id)
        ON DELETE RESTRICT,
    employee_id BIGINT REFERENCES employee(employee_id)
        ON DELETE RESTRICT,
    status_id BIGINT NOT NULL REFERENCES request_status(status_id)
        ON DELETE RESTRICT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- employee_id is nullable to support initial/system-generated events.

-- 8. Assignment and decision history
CREATE TABLE IF NOT EXISTS request_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_request(request_id)
        ON DELETE RESTRICT,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id)
        ON DELETE RESTRICT,
    assigned_by_employee_id BIGINT NOT NULL
        REFERENCES employee(employee_id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decision VARCHAR(20) NOT NULL DEFAULT 'Pending',
    decision_at TIMESTAMPTZ,
    rejection_comment TEXT,
    CONSTRAINT assignment_decision_valid
        CHECK (decision IN ('Pending', 'Accepted', 'Rejected')),
    CONSTRAINT assignment_decision_timestamp
        CHECK (
            (decision = 'Pending' AND decision_at IS NULL)
            OR
            (decision IN ('Accepted', 'Rejected')
                AND decision_at IS NOT NULL)
        ),
    CONSTRAINT assignment_rejection_comment
        CHECK (
            decision <> 'Rejected'
            OR LENGTH(TRIM(COALESCE(rejection_comment, ''))) > 0
        )
);

-- 9. Notifications
CREATE TABLE IF NOT EXISTS notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_request(request_id)
        ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at TIMESTAMPTZ,
    CONSTRAINT notification_status_valid
        CHECK (status IN ('Pending', 'Sent', 'Failed')),
    CONSTRAINT notification_sent_timestamp
        CHECK (
            (status = 'Sent' AND sent_at IS NOT NULL)
            OR
            (status <> 'Sent' AND sent_at IS NULL)
        )
);

-- Useful indexes for common request searches.
CREATE INDEX IF NOT EXISTS ix_request_requester
    ON service_request(requester_id);

CREATE INDEX IF NOT EXISTS ix_request_status
    ON service_request(current_status_id);

CREATE INDEX IF NOT EXISTS ix_request_category
    ON service_request(category_id);

CREATE INDEX IF NOT EXISTS ix_request_assigned_employee
    ON service_request(assigned_employee_id);

CREATE INDEX IF NOT EXISTS ix_history_request_time
    ON request_status_history(request_id, changed_at);

CREATE INDEX IF NOT EXISTS ix_assignment_request_time
    ON request_assignment(request_id, assigned_at);

CREATE INDEX IF NOT EXISTS ix_notification_request_time
    ON notification(request_id, created_at);

